#!/usr/bin/env python3
"""Fold the v2 generation run into the published premise tags, and say which strings are new.

  pipeline/merge_premise_tags.py --phase out-premise-v2/gen --out data/premise-tags-v2.json
  pipeline/merge_premise_tags.py --into data/premise-tags-v2.json --phase A/gen --phase B \
      --note "extended by ..." --embed-list embed.json      # a later run, appended to v2

The first form builds v2 from v1 and ran once. Every later run appends with `--into`.

v1 is NOT overwritten. `vectors-premise.bin` is aligned to v1's tag strings, so rewriting them in place
would leave every vector describing text that no longer exists — a blob paired with the wrong strings, in
a form no checksum would catch.

## Keying

`build-premise-tags.py` recovers a title's mediaType POSITIONALLY, because the v1 batches carry a bare
tmdbId and 1,097 ids in this corpus are both a film and a series. This run's batches carry `movie:123` /
`tv:123` keys directly, so there is nothing to recover and nothing to guess. The merge refuses any key it
cannot parse rather than falling back to a bare id.

## The two repairs

`validate_premise_batch.py` reports per-tag problems it deliberately does not reject a batch for, because
they are mechanical:

  * a tag that only needs normalising (`cinecittà-ambition` -> `cinecitta-ambition`) is REPAIRED. The
    index is ASCII; a tag with an accent in it joins against nothing, and dropping it would throw away a
    real premise over a typo.
  * a tag that is nothing but genre words (`romantic-comedy`, `comedy-adventure-sci-fi`) is DROPPED. It
    restates what the taxonomy labels already record, and `data/README.md` credits that ban with why this
    index beats the plot index by +11.3 pp.
  * a tag naming a storytelling property (`character-arc`, `plot-twist`, `emotional-journey`) is DROPPED
    for a sharper reason: it is true of nearly every narrative, so it does not merely waste a slot, it
    drags unrelated titles together. The six batches that produced these in bulk were re-run; dropping
    here covers the long tail of one or two per batch, where a re-run would pay for 21 good rows to fix
    one tag.

A drop can take a title below the spec's 8-tag floor. That is reported, not fixed: re-running the title
costs a model call for something a short tag list still answers, and a title with 7 real tags is worth
more than one with 7 real tags and `romantic-comedy`.

## What gets embedded

Only titles whose composed string CHANGED. A title already in v1 whose v2 tags are identical keeps its
existing vector, so the embed cost is the new titles plus the repaired ones, not the whole corpus.
"""
import argparse
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location("v", os.path.join(HERE, "validate_premise_batch.py"))
_v = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_v)


def compose(tags):
    """The embedding document for a title: tags, most-defining first, space separated.

    Identical to the v1 composition (pipeline/embed_tags.py) so a v1-vs-v2 comparison measures the tags
    and not the formatting. Hyphens stay — bge-m3 sub-word tokenizes them, and splitting a compound
    premise into its parts measurably blurs it.
    """
    return " ".join(tags)


def clean(tags):
    """Apply the two mechanical repairs; return (kept, repaired, dropped)."""
    kept, repaired, dropped = [], [], []
    for t in tags:
        if not isinstance(t, str) or not t.strip():
            continue
        fixed = _v.normalise(t)
        if fixed != t:
            if not _v.TAG.match(fixed) or _v.has_non_ascii(fixed):
                dropped.append(t)
                continue
            repaired.append((t, fixed))
            t = fixed
        if _v.genre_words(t) or t in _v.VAGUE_TAGS:
            dropped.append(t)
            continue
        if t not in kept:  # a repair can collide with a tag already present
            kept.append(t)
    return kept, repaired, dropped


def read_phases(phases):
    """Every generated row across the phases, cleaned; exits on a key it cannot trust."""
    new, repairs, drops, below_floor = {}, 0, 0, []
    for phase in phases:
        for name in sorted(os.listdir(os.path.join(phase, "out"))):
            if not (name.startswith("batch-") and name.endswith(".json")):
                continue
            for row in json.load(open(os.path.join(phase, "out", name), encoding="utf-8")):
                if not isinstance(row, dict):
                    continue
                key = row.get("key")
                if not isinstance(key, str) or key.count(":") != 1 or key.split(":")[0] not in ("movie", "tv"):
                    sys.exit(f"{name}: unusable key {key!r} — refusing to guess mediaType")
                if key in new:
                    sys.exit(f"{phase}/out/{name}: {key} was already generated by an earlier batch or phase — "
                             f"refusing to pick one")
                kept, rep, drp = clean(row.get("tags") or [])
                repairs += len(rep)
                drops += len(drp)
                if not kept:
                    sys.exit(f"{name}: {key} has no tags left after cleaning — refusing to write an empty record")
                if len(kept) < _v.MIN_TAGS:
                    below_floor.append(key)
                new[key] = kept
    return new, repairs, drops, below_floor


ap = argparse.ArgumentParser()
ap.add_argument("--phase", required=True, action="append",
                help="the gen/ directory holding in/ and out/; repeat to merge several runs")
ap.add_argument("--v1", default="data/premise-tags-v1.json")
ap.add_argument("--extra", default="out-premise-999/tags.json",
                help="tags that exist only in a gitignored working dir but ARE in the published index")
ap.add_argument("--into", help="APPEND to this v2 file instead of rebuilding v2 from v1 (see append_into)")
ap.add_argument("--overwrite", action="store_true",
                help="with --into: replace a title the file already holds instead of refusing")
ap.add_argument("--note", help="with --into: the clause appended to derivedFrom naming this run")
ap.add_argument("--out", help="default: the --into file")
ap.add_argument("--embed-list", help="write the keys whose string changed, for the embed run")
args = ap.parse_args()


def append_into():
    """Add a later run's titles to an existing v2 file, leaving every record it already holds untouched.

    Rebuilding from v1 is wrong once v2 is the committed file: passing v2 as `--v1` would append the v2
    clause to derivedFrom a second time and set `supersedes` to v2's own index. So this keeps v2's metadata
    as it is, adds the new keys, and appends one clause (`--note`) saying where they came from.

    The existing records are not re-cleaned: the v1 repairs already rode along when v2 was built, and
    leaving them alone keeps the diff to the added keys. A key the file already holds is refused unless
    `--overwrite` says to replace it — a silent replacement changes a live string and needs a re-embed
    nobody asked for.
    """
    if not args.note:
        sys.exit("--into needs --note: the derivedFrom clause naming this run")
    into = json.load(open(args.into, encoding="utf-8"))
    tags = dict(into["tags"])
    new, repairs, drops, below_floor = read_phases(args.phase)
    present = sorted(k for k in new if k in tags)
    if present and not args.overwrite:
        sys.exit(f"{len(present)} key(s) already in {args.into}, e.g. {present[:5]} — pass --overwrite to "
                 f"replace them")
    changed = sorted(k for k, t in new.items() if k not in tags or compose(t) != compose(tags[k]))
    tags.update(new)
    out = dict(into, count=len(tags), tags=tags, derivedFrom=f"{into['derivedFrom']}; {args.note}")
    path = args.out or args.into
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=1, sort_keys=True)
    if args.embed_list:
        with open(args.embed_list, "w", encoding="utf-8") as fh:
            json.dump(changed, fh, indent=1)
    print(json.dumps({
        "before": len(into["tags"]), "generated": len(new), "after": len(tags),
        "addedTitles": len(tags) - len(into["tags"]), "overwrittenTitles": len(present),
        "tagsRepaired": repairs, "tagsDropped": drops,
        "titlesBelowFloorAfterDrop": len(below_floor), "belowFloor": below_floor,
        "stringsToEmbed": len(changed), "out": path, "embedList": args.embed_list,
    }, indent=2))


if args.into:
    append_into()
    sys.exit(0)
if not args.out:
    sys.exit("--out is required unless --into is given")

v1 = json.load(open(args.v1, encoding="utf-8"))
old_tags = dict(v1["tags"])

# The published index carries 999 titles that `data/premise-tags-v1.json` does not: they were generated
# into a gitignored working dir and merged straight into the blob. Leaving them out here would not just
# lose them — it would SHRINK live premise coverage by 999 titles while appearing to grow it by 5,999.
# The generation worklist already skipped them for exactly this reason (build_premise_worklist.load_have),
# so they are re-joined here rather than regenerated.
extra_count = 0
if args.extra and os.path.exists(args.extra):
    extra = json.load(open(args.extra, encoding="utf-8"))
    if not isinstance(extra, dict):
        extra = {f"{r['mediaType']}:{r['tmdbId']}": r["tags"] for r in extra}
    for k, t in extra.items():
        if k not in old_tags:
            old_tags[k] = t
            extra_count += 1
elif args.extra:
    sys.exit(f"{args.extra} is missing — it holds 999 titles that are in the published index and nowhere "
             f"else; merging without it would silently drop them from premise coverage")

new, repairs, drops, below_floor = read_phases(args.phase)

# v1 carries 145 tags that are not tags: `suspected-wife's-affair`, `found-family-of-protégés`. An
# apostrophe or an accent joins against nothing in an ASCII index, so those slots have been dead since the
# corpus shipped. They are repaired here rather than left alone because v2 re-embeds anyway — the repair
# rides along in the embed list at the cost of the ~140 titles carrying one, and leaving them would mean
# knowingly publishing a new index with known-dead terms in it. A v1 tag that does NOT normalise to a valid
# tag is dropped on the same rule as the new run's.
v1_repairs, v1_drops, v1_touched = 0, 0, 0
carried = {}
for key, tags in old_tags.items():
    kept, rep, drp = clean(tags)
    if not kept:                      # never observed; keep the original rather than empty a record
        carried[key] = tags
        continue
    if kept != tags:
        v1_touched += 1
        v1_repairs += len(rep)
        v1_drops += len(drp)
    carried[key] = kept

merged = dict(carried)
overwritten = sum(1 for k in new if k in merged)
merged.update(new)

changed = [k for k, t in merged.items()
           if k not in old_tags or compose(t) != compose(old_tags[k])]

out = {
    "schema": v1["schema"],
    "index": "premise-v2",
    "count": len(merged),
    "derivedFrom": (v1["derivedFrom"] + "; extended by the v2 run over the re-ground Wikipedia corpus, "
                    "spec data/premise-tags-v1.SPEC.md, evidence limited to Jev-classified story-premise "
                    "and theme-subject sections"),
    "embeddedBy": v1["embeddedBy"],
    "supersedes": v1["index"],
    "tags": merged,
    # Carried forward verbatim: in v1 these titles had tags and no vector because the DT-N merge never ran.
    # The v2 blob covers them — `embed_premise_v2.py` embeds every title in this file.
    "coverageFilled": v1.get("coverageFilled", []),
    "vectorsMissingFor": v1.get("vectorsMissingFor", []),
}
os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
json.dump(out, open(args.out, "w", encoding="utf-8"), indent=1, sort_keys=True)

if args.embed_list:
    json.dump(sorted(changed), open(args.embed_list, "w", encoding="utf-8"), indent=1)

print(json.dumps({
    "v1Titles": len(old_tags), "fromExtraWorkingDir": extra_count, "v2Generated": len(new), "merged": len(merged),
    "addedTitles": len(merged) - len(old_tags), "overwrittenTitles": overwritten,
    "tagsRepaired": repairs, "tagsDropped": drops,
    "v1TitlesTouched": v1_touched, "v1TagsRepaired": v1_repairs, "v1TagsDropped": v1_drops,
    "titlesBelowFloorAfterDrop": len(below_floor), "belowFloorSample": below_floor[:8],
    "stringsToEmbed": len(changed),
    "out": args.out, "embedList": args.embed_list,
}, indent=2))
